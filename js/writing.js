/* ========== WRITING PAGE ==========
   Renders the article list and category filters from articles.json.
   That file is generated by `python3 scripts/build_writing.py` from
   writing/articles/*.md and is already sorted newest first. */
(function () {
    const INDEX_URL = "articles.json";
    const ALL = "All";
    const MONTH_YEAR = new Intl.DateTimeFormat("en-GB", { month: "long", year: "numeric", timeZone: "UTC" });

    const list = document.getElementById("post-list");
    const filters = document.getElementById("filters");
    const status = document.getElementById("posts-status");
    if (!list) return;

    let articles = [];
    let current = ALL;

    function el(tag, className, text) {
        const node = document.createElement(tag);
        if (className) node.className = className;
        if (text != null) node.textContent = text;
        return node;
    }

    function renderFilters(categories) {
        const options = [{ name: ALL, count: articles.length }].concat(categories);
        options.forEach(function (cat) {
            const btn = el("button", "filter", cat.name);
            btn.type = "button";
            btn.dataset.category = cat.name;
            btn.setAttribute("aria-pressed", String(cat.name === current));
            btn.append(" ", el("span", "filter-count", String(cat.count)));
            filters.appendChild(btn);
        });
        filters.hidden = false;
    }

    function renderPosts() {
        const shown = current === ALL ? articles : articles.filter(function (a) { return a.category === current; });
        list.replaceChildren();

        shown.forEach(function (a, i) {
            const item = el("li", "post");
            item.style.setProperty("--i", i);

            const link = el("a", "post-link");
            link.href = a.url;

            const meta = el("p", "post-meta");
            const time = el("time", null, MONTH_YEAR.format(new Date(a.date)));
            time.dateTime = a.date;
            meta.append(time, el("span", "post-category", a.category), el("span", null, a.reading_time + " min read"));

            const title = el("h2", "post-title", a.title);
            const arrow = el("span", "post-arrow", "→");
            arrow.setAttribute("aria-hidden", "true");
            title.appendChild(arrow);

            // One wrapper so meta, title and description shift together on hover
            const body = el("div", "post-body");
            body.append(meta, title);
            if (a.description) body.appendChild(el("p", "post-desc", a.description));
            link.appendChild(body);
            item.appendChild(link);
            list.appendChild(item);
        });

        status.textContent = shown.length ? "" : "Nothing published here yet.";
        status.hidden = shown.length > 0;
    }

    filters.addEventListener("click", function (e) {
        const btn = e.target.closest(".filter");
        if (!btn || btn.dataset.category === current) return;
        current = btn.dataset.category;
        filters.querySelectorAll(".filter").forEach(function (b) {
            b.setAttribute("aria-pressed", String(b === btn));
        });
        renderPosts();
    });

    fetch(INDEX_URL, { cache: "no-cache" })
        .then(function (res) {
            if (!res.ok) throw new Error(res.status);
            return res.json();
        })
        .then(function (data) {
            articles = data.articles || [];
            if (articles.length) renderFilters(data.categories || []);
            renderPosts();
        })
        .catch(function () {
            status.textContent = "Couldn't load the articles. Please try again later.";
        });
})();
