#!/usr/bin/env python3
"""Build the Writing section from Markdown articles.

Run from anywhere (standard library only, no dependencies):

    python3 scripts/build_writing.py

It reads every writing/articles/*.md file and:
  1. parses the front matter (title, slug, date, description, category, tags, ...)
  2. skips drafts (`draft: true` or `published: false`)
  3. renders each article to writing/<slug>/index.html (served at /writing/<slug>/)
     using scripts/templates/article.html
  4. writes writing/articles.json: every published article, newest first, plus the
     categories currently in use (read by js/writing.js to build the filters)
  5. removes pages it generated earlier for articles that no longer exist or are drafts
"""

import html
import json
import math
import re
import sys
from datetime import date
from pathlib import Path
from string import Template

ROOT = Path(__file__).resolve().parent.parent
WRITING_DIR = ROOT / "writing"
SOURCE_DIR = WRITING_DIR / "articles"
INDEX_FILE = WRITING_DIR / "articles.json"
TEMPLATE_FILE = Path(__file__).resolve().parent / "templates" / "article.html"

SITE_URL = "https://itsleontan.com"
WORDS_PER_MINUTE = 200
EXCERPT_LENGTH = 180
DEFAULT_CATEGORY = "Uncategorised"
# Written into every generated page so stale pages can be cleaned up safely.
MARKER = "<!-- Generated by scripts/build_writing.py from writing/articles/. Edit the Markdown, not this file. -->"
RESERVED_SLUGS = {"articles"}
SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")


class BuildError(Exception):
    pass


# ==========================================================================
# FRONT MATTER (the small YAML subset used by the articles)
# ==========================================================================
def parse_scalar(value):
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1]
    if value.startswith("[") and value.endswith("]"):
        return [parse_scalar(v) for v in value[1:-1].split(",") if v.strip()]
    lowered = value.lower()
    if lowered in ("true", "yes"):
        return True
    if lowered in ("false", "no"):
        return False
    return value


def parse_front_matter(lines):
    data, key = {}, None
    for raw in lines:
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        item = re.match(r"^\s*-\s+(.*)$", raw)
        if item and key is not None:
            if not isinstance(data[key], list):
                data[key] = []
            data[key].append(parse_scalar(item.group(1)))
            continue
        pair = re.match(r"^([A-Za-z_][\w-]*)\s*:\s*(.*)$", raw)
        if not pair:
            raise BuildError(f"cannot parse front matter line: {raw!r}")
        key, value = pair.group(1), pair.group(2)
        data[key] = parse_scalar(value) if value.strip() else []
    return data


def split_front_matter(text):
    text = text.replace("\r\n", "\n").lstrip("﻿").lstrip()
    if not text.startswith("---"):
        return {}, text
    lines = text.split("\n")
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            return parse_front_matter(lines[1:i]), "\n".join(lines[i + 1:])
    raise BuildError("front matter is not closed with ---")


# ==========================================================================
# MARKDOWN -> HTML
# Covers what the articles use: headings, paragraphs, (nested) lists, fenced
# code, blockquotes, rules, bold/italic/strike, inline code, links, images.
# Raw HTML in the Markdown is escaped, not passed through.
# ==========================================================================
FENCE_RE = re.compile(r"^\s*(```+|~~~+)\s*([\w+#.-]*)\s*$")
HEADING_RE = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
HR_RE = re.compile(r"^\s*([-*_])(\s*\1){2,}\s*$")
LIST_RE = re.compile(r"^(\s*)([-*+]|\d{1,9}[.)])\s+(.*)$")
QUOTE_RE = re.compile(r"^\s*>\s?(.*)$")


def slugify(text):
    text = re.sub(r"<[^>]+>", "", text).lower()
    text = re.sub(r"&[a-z]+;|&#\d+;", "", text)
    return re.sub(r"[^a-z0-9]+", "-", text).strip("-") or "section"


def indent_of(line):
    return len(line) - len(line.lstrip(" "))


def is_block_start(line):
    return bool(FENCE_RE.match(line) or HEADING_RE.match(line) or HR_RE.match(line)
                or LIST_RE.match(line) or QUOTE_RE.match(line))


def render_inline(text):
    stash = []

    def keep(fragment):
        stash.append(fragment)
        return f"\x00{len(stash) - 1}\x00"

    text = re.sub(r"(`+)(.+?)\1",
                  lambda m: keep("<code>" + html.escape(m.group(2).strip(), quote=False) + "</code>"), text)
    text = html.escape(text, quote=False)

    def emphasis(s):
        s = re.sub(r"\*\*(?=\S)(.+?)(?<=\S)\*\*", r"<strong>\1</strong>", s)
        s = re.sub(r"(?<!\w)__(?=\S)(.+?)(?<=\S)__(?!\w)", r"<strong>\1</strong>", s)
        s = re.sub(r"(?<![\w*])\*(?=\S)(.+?)(?<=\S)\*(?![\w*])", r"<em>\1</em>", s)
        s = re.sub(r"(?<!\w)_(?=\S)(.+?)(?<=\S)_(?!\w)", r"<em>\1</em>", s)
        return re.sub(r"~~(?=\S)(.+?)(?<=\S)~~", r"<del>\1</del>", s)

    def attr(value):
        return value.replace('"', "&quot;")

    def image(m):
        alt, src = m.group(1), m.group(2)
        return keep(f'<img src="{attr(src)}" alt="{attr(alt)}" loading="lazy">')

    def link(m):
        label, href = m.group(1), m.group(2)
        external = re.match(r"^https?://", href)
        extra = ' target="_blank" rel="noopener noreferrer"' if external else ""
        return keep(f'<a href="{attr(href)}"{extra}>{emphasis(label)}</a>')

    text = re.sub(r'!\[([^\]]*)\]\(([^)\s]+)(?:\s+"[^"]*")?\)', image, text)
    text = re.sub(r'\[([^\]]+)\]\(([^)\s]+)(?:\s+"[^"]*")?\)', link, text)
    text = re.sub(r"&lt;(https?://[^\s<>]+?)&gt;",
                  lambda m: keep(f'<a href="{attr(m.group(1))}" target="_blank" rel="noopener noreferrer">{m.group(1)}</a>'),
                  text)
    text = emphasis(text)
    text = re.sub(r"(?: {2,}|\\)\n", "<br>\n", text)

    while "\x00" in text:
        text = re.sub(r"\x00(\d+)\x00", lambda m: stash[int(m.group(1))], text)
    return text


def render_list(lines, i, ids):
    first = LIST_RE.match(lines[i])
    base = indent_of(lines[i])
    ordered = first.group(2)[0].isdigit()
    items, loose = [], False

    while i < len(lines):
        m = LIST_RE.match(lines[i])
        if not m or indent_of(lines[i]) != base or m.group(2)[0].isdigit() != ordered:
            break
        content_indent = len(m.group(1)) + len(m.group(2)) + 1
        body = [m.group(3)]
        i += 1
        while i < len(lines):
            line = lines[i]
            if not line.strip():
                nxt = next((j for j in range(i + 1, len(lines)) if lines[j].strip()), None)
                if nxt is None:
                    i = len(lines)
                    break
                if indent_of(lines[nxt]) > base:
                    loose = True
                    body.append("")
                    i += 1
                    continue
                n = LIST_RE.match(lines[nxt])
                if n and indent_of(lines[nxt]) == base and n.group(2)[0].isdigit() == ordered:
                    loose = True
                    i = nxt
                break
            if indent_of(line) > base:
                body.append(line[min(indent_of(line), content_indent):])
            elif not is_block_start(line) and body[-1].strip():
                body.append(line)  # lazy paragraph continuation
            else:
                break
            i += 1
        items.append(body)

    rendered = []
    for body in items:
        blocks = render_blocks(body, ids)
        if not loose:
            blocks = [b[3:-4] if b.startswith("<p>") and b.endswith("</p>") else b for b in blocks]
        rendered.append("<li>" + "\n".join(blocks) + "</li>")

    tag = "ol" if ordered else "ul"
    start = int(re.match(r"\d+", first.group(2)).group()) if ordered else 1
    start_attr = f' start="{start}"' if start != 1 else ""
    return f"<{tag}{start_attr}>\n" + "\n".join(rendered) + f"\n</{tag}>", i


def render_blocks(lines, ids):
    out, i = [], 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
            continue

        fence = FENCE_RE.match(line)
        if fence:
            marker, lang = fence.group(1), fence.group(2)
            code, i = [], i + 1
            while i < len(lines) and not lines[i].strip().startswith(marker):
                code.append(lines[i])
                i += 1
            i += 1
            cls = f' class="language-{html.escape(lang)}"' if lang else ""
            escaped = html.escape("\n".join(code), quote=False)
            out.append(f"<pre><code{cls}>{escaped}</code></pre>")
            continue

        heading = HEADING_RE.match(line)
        if heading:
            level, content = len(heading.group(1)), render_inline(heading.group(2))
            anchor = slugify(content)
            base, n = anchor, 2
            while anchor in ids:
                anchor, n = f"{base}-{n}", n + 1
            ids.add(anchor)
            out.append(f'<h{level} id="{anchor}">{content}</h{level}>')
            i += 1
            continue

        if HR_RE.match(line):
            out.append("<hr>")
            i += 1
            continue

        if QUOTE_RE.match(line):
            quoted = []
            while i < len(lines) and lines[i].strip():
                q = QUOTE_RE.match(lines[i])
                quoted.append(q.group(1) if q else lines[i])
                i += 1
            out.append("<blockquote>\n" + "\n".join(render_blocks(quoted, ids)) + "\n</blockquote>")
            continue

        if LIST_RE.match(line):
            block, i = render_list(lines, i, ids)
            out.append(block)
            continue

        para = [line.strip()]
        i += 1
        while i < len(lines) and lines[i].strip() and not is_block_start(lines[i]):
            # keep two trailing spaces so hard line breaks survive
            para.append(lines[i].lstrip().rstrip("\n"))
            i += 1
        out.append("<p>" + render_inline("\n".join(para).strip()) + "</p>")
    return out


def render_markdown(markdown):
    return "\n".join(render_blocks(markdown.split("\n"), set()))


# ==========================================================================
# ARTICLES
# ==========================================================================
def plain_text(markdown):
    text = re.sub(r"^\s*(```|~~~).*?^\s*\1\s*$", " ", markdown, flags=re.S | re.M)
    text = re.sub(r"!\[[^\]]*\]\([^)]*\)", " ", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"^\s{0,3}(#{1,6}|>|[-*+]|\d+[.)])\s+", "", text, flags=re.M)
    text = re.sub(r"[*_`~]", "", text)
    return text


def reading_time(markdown):
    # Code is counted too: it takes time to read, just differently.
    words = len(re.findall(r"[\w'’-]+", re.sub(r"[`*_#>~]", " ", markdown)))
    return max(1, math.ceil(words / WORDS_PER_MINUTE))


def excerpt(markdown):
    for para in re.split(r"\n\s*\n", markdown):
        if para.strip() and not is_block_start(para.strip().split("\n")[0]):
            text = " ".join(plain_text(para).split())
            if len(text) <= EXCERPT_LENGTH:
                return text
            return text[:EXCERPT_LENGTH].rsplit(" ", 1)[0].rstrip(",.;:") + "…"
    return ""


def parse_date(value, field, path):
    if isinstance(value, str) and value.strip():
        try:
            return date.fromisoformat(value.strip()[:10])
        except ValueError:
            pass
    raise BuildError(f"{path.name}: '{field}' must be a date like 2026-11-24 (got {value!r})")


def text_field(meta, key):
    value = meta.get(key, "")
    return value.strip() if isinstance(value, str) else ""


def load_article(path):
    meta, body = split_front_matter(path.read_text(encoding="utf-8"))

    if meta.get("draft") is True or meta.get("published") is False:
        return None

    # The page renders the title itself, so a leading "# Title" is dropped.
    body = body.strip("\n")
    leading = re.match(r"^#\s+(.+?)\s*#*\s*(\n|$)", body)
    title = text_field(meta, "title")
    if leading:
        title = title or leading.group(1).strip()
        body = body[leading.end():].lstrip("\n")
    if not title:
        raise BuildError(f"{path.name}: missing 'title'")

    slug = text_field(meta, "slug") or path.stem
    if not SLUG_RE.match(slug) or slug in RESERVED_SLUGS:
        raise BuildError(f"{path.name}: slug {slug!r} must be lowercase words joined by hyphens "
                         f"(and not one of {sorted(RESERVED_SLUGS)})")

    published = parse_date(meta.get("date"), "date", path)
    modified = parse_date(meta["last_modified"], "last_modified", path) if text_field(meta, "last_modified") else None

    tags = meta.get("tags") or []
    if isinstance(tags, str):
        tags = [tags]

    return {
        "title": title,
        "slug": slug,
        "url": f"{slug}/",
        "date": published.isoformat(),
        "last_modified": modified.isoformat() if modified and modified > published else None,
        "category": text_field(meta, "category") or DEFAULT_CATEGORY,
        "description": text_field(meta, "description") or excerpt(body),
        "reading_time": reading_time(body),
        "tags": [str(t).strip() for t in tags if str(t).strip()],
        "source": path.relative_to(ROOT).as_posix(),
        "_body": body,
    }


def long_date(iso):
    d = date.fromisoformat(iso)
    return f"{d.day} {d.strftime('%B %Y')}"


def render_page(template, article):
    e = lambda s: html.escape(s, quote=True)
    tags = "".join(f'<li>{e(t)}</li>' for t in article["tags"])
    updated = ""
    if article["last_modified"]:
        updated = (f'<p class="article-updated">Last updated '
                   f'<time datetime="{article["last_modified"]}">{long_date(article["last_modified"])}</time></p>')
    return template.substitute(
        marker=MARKER,
        title=e(article["title"]),
        description=e(article["description"]),
        canonical=f'{SITE_URL}/writing/{article["url"]}',
        date_iso=article["date"],
        date_long=long_date(article["date"]),
        category=e(article["category"]),
        reading_time=article["reading_time"],
        content=render_markdown(article["_body"]),
        tags=f'<ul class="article-tags" aria-label="Tags">{tags}</ul>' if tags else "",
        updated=updated,
    )


def build():
    if not SOURCE_DIR.is_dir():
        raise BuildError(f"no articles directory at {SOURCE_DIR}")
    template = Template(TEMPLATE_FILE.read_text(encoding="utf-8"))

    articles, skipped = [], []
    for path in sorted(SOURCE_DIR.glob("*.md")):
        article = load_article(path)
        (articles.append(article) if article else skipped.append(path.name))

    seen = {}
    for a in articles:
        if a["slug"] in seen:
            raise BuildError(f"duplicate slug {a['slug']!r} in {seen[a['slug']]} and {a['source']}")
        seen[a["slug"]] = a["source"]

    # Categories are matched case-insensitively; the first spelling wins.
    spelling = {}
    for a in articles:
        a["category"] = spelling.setdefault(a["category"].casefold(), a["category"])

    # Newest first; title breaks ties so the order is stable.
    articles.sort(key=lambda a: a["title"].casefold())
    articles.sort(key=lambda a: a["date"], reverse=True)

    counts = {}
    for a in articles:
        counts[a["category"]] = counts.get(a["category"], 0) + 1
    categories = [{"name": name, "count": counts[name]} for name in sorted(counts, key=str.casefold)]

    for a in articles:
        out_dir = WRITING_DIR / a["slug"]
        out_dir.mkdir(exist_ok=True)
        (out_dir / "index.html").write_text(render_page(template, a), encoding="utf-8")

    # Remove pages generated earlier for articles that were deleted or drafted.
    removed = []
    for page in WRITING_DIR.glob("*/index.html"):
        slug = page.parent.name
        if slug not in seen and MARKER in page.read_text(encoding="utf-8"):
            page.unlink()
            if not any(page.parent.iterdir()):
                page.parent.rmdir()
            removed.append(slug)

    index = {
        "categories": categories,
        "articles": [{k: v for k, v in a.items() if not k.startswith("_")} for a in articles],
    }
    INDEX_FILE.write_text(json.dumps(index, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    print(f"Built {len(articles)} article(s) -> {INDEX_FILE.relative_to(ROOT)}")
    for a in articles:
        print(f"  {a['date']}  {a['category']:<16} {a['reading_time']:>2} min  /writing/{a['url']}")
    print("Categories: " + (", ".join(f"{c['name']} ({c['count']})" for c in categories) or "none"))
    if skipped:
        print("Skipped drafts: " + ", ".join(skipped))
    if removed:
        print("Removed stale pages: " + ", ".join(f"/writing/{s}/" for s in removed))


if __name__ == "__main__":
    try:
        build()
    except BuildError as err:
        sys.exit(f"build_writing: {err}")
